import assert from 'node:assert/strict'
export async function proveCompanyBrowser(origin,page) {
 for(const width of [1440,390]) {
  await page.setViewportSize({width,height:1000});await page.goto(origin+'/app/company')
  await page.getByRole('status').filter({hasText:'US conventions loaded'}).waitFor()
  await page.getByLabel('Company name',{exact:true}).fill('Synthetic Bifocal Supply '+width)
  await page.getByRole('button',{name:'Save company',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Company conventions saved'}).waitFor()
  const shot=async state=>{assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${state} overflow ${width}`);if(process.env.BIFOCAL_PROOF_DIR)await page.screenshot({path:`${process.env.BIFOCAL_PROOF_DIR}/company-${state}-${width}.png`,fullPage:true})}
  await shot('settings')
  await page.getByLabel('Calendar id',{exact:true}).fill(`synthetic-bifocal-ui-july-${width}`)
  await page.getByLabel('Calendar name',{exact:true}).fill('July fiscal')
  await page.getByLabel('Start month',{exact:true}).fill('7')
  await page.getByLabel('Fiscal start year',{exact:true}).fill('2023')
  await page.getByRole('button',{name:'Save calendar and inspect year',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Calendar saved and year resolved'}).waitFor()
  assert.match(await page.locator('#calendar-result').innerText(),/366/);assert.match(await page.locator('#calendar-result').innerText(),/2024-07-01/)
  await shot('july')
  await page.getByLabel('Calendar id',{exact:true}).fill(`synthetic-bifocal-ui-retail-${width}`)
  await page.getByLabel('Calendar type',{exact:true}).selectOption('445')
  await page.getByLabel('Start month',{exact:true}).fill('2')
  await page.getByRole('button',{name:'Save calendar and inspect year',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Calendar saved and year resolved'}).waitFor()
  assert.match(await page.locator('#calendar-result').innerText(),/53/)
  await page.getByLabel('Start date (MM/DD/YYYY)',{exact:true}).fill('07/02/2026');await page.getByLabel('End date, exclusive (MM/DD/YYYY)',{exact:true}).fill('07/07/2026')
  await page.getByRole('button',{name:'Calculate working days',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Holiday-adjusted measure calculated'}).waitFor()
  assert.match(await page.locator('#working-result').innerText(),/2 working days/);assert.match(await page.locator('#working-result').innerText(),/Independence Day/)
  await shot('retail-holiday')
  await page.getByLabel('Rate source id',{exact:true}).fill(`synthetic-bifocal-ui-rates-${width}`)
  await page.getByLabel('Rate source name',{exact:true}).fill('Treasury reference')
  await page.getByLabel('Rate use authorization',{exact:true}).fill('Owner supplied for internal use')
  await page.getByLabel('Dated rates (JSON array)',{exact:true}).fill(JSON.stringify([{currency:'EUR',date:'2026-06-19',rate:'0.8'}]))
  await page.getByRole('button',{name:'Save rate source',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Named rate source saved'}).waitFor()
  await page.getByLabel('Original transactions (JSON array)',{exact:true}).fill(JSON.stringify([{id:'synthetic-bifocal-60',amount:'100.00',currency:'EUR',date:'2026-06-19'},{id:'synthetic-bifocal-61',amount:'100.00',currency:'USD',date:'2026-06-19'}]))
  await page.getByRole('button',{name:'Convert to USD',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Exact USD conversion calculated'}).waitFor()
  assert.match(await page.locator('#conversion-result').innerText(),/225\.00/);assert.match(await page.locator('#conversion-result').innerText(),/EUR/)
  await shot('currency')
  const structure=await page.locator('main').ariaSnapshot();assert.match(structure,/heading "Company conventions"/);assert.match(structure,/button "Convert to USD"/)
 }
 console.log('Company browser: US setup, July and 53-week retail calendars, holiday measure and exact USD/EUR conversion at 1440/390 passed')
}
