import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
export async function proveFileBrowser(origin, context, page, workbookBytes) {
 const csv = 'id,date,region,amount\n1,01/15/2026,West,$1234.56\n2,01/16/2026,East,-$25.50\n'
 for (const width of [1440,390]) {
  const dataset = `synthetic-bifocal-ui-${width}`
  await page.setViewportSize({width,height:1000}); await page.goto(origin + '/app')
  await page.getByRole('link',{name:'Files',exact:true}).click()
  await page.getByRole('heading',{name:'Import files',exact:true}).waitFor()
  await page.getByLabel('Dataset id',{exact:true}).fill(dataset)
  const file = page.getByLabel('CSV or XLSX file',{exact:true})
  await file.setInputFiles({name:'synthetic-bifocal-30.csv',mimeType:'text/csv',buffer:Buffer.from(csv)})
  await page.getByLabel('Key column (optional)',{exact:true}).fill('id')
  const shot = async state => {
   if(process.env.BIFOCAL_PROOF_DIR)await page.screenshot({path:`${process.env.BIFOCAL_PROOF_DIR}/files-${state}-${width}.png`,fullPage:true})
   const overflow=await page.evaluate(()=>({width:innerWidth,document:document.documentElement.scrollWidth,elements:[...document.querySelectorAll('main *')].filter(node=>node.getBoundingClientRect().right>innerWidth+1 && !node.closest('.tablewrap')).map(node=>({tag:node.tagName,id:node.id,right:node.getBoundingClientRect().right})).slice(0,10)}))
   assert.ok(overflow.document<=width,`${state} overflow ${width}: ${JSON.stringify(overflow)}`)
  }
  await shot('prepare')
  await page.getByRole('button',{name:'Preview import',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Plan ready'}).waitFor()
  assert.match(await page.locator('#plan-summary').innerText(),/Detected candidate keys/)
  assert.match(await page.locator('#sample').innerText(),/1234\.56/)
  assert.match(await page.locator('#source').innerText(),/literal-text/)
  await shot('review')
  await page.getByLabel('I reviewed this exact plan and its fingerprint',{exact:true}).check()
  await page.getByRole('button',{name:'Apply import',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Import completed and reconciled'}).waitFor()
  let current=await(await context.request.get(`${origin}/api/operator/datasets/${dataset}`)).json()
  assert.equal(current.table.rows.length,2)
  await page.locator('#current').scrollIntoViewIfNeeded(); await shot('completed')
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Download original',exact:true}).first().click();const download=await downloadPromise;assert.equal(download.suggestedFilename(),'synthetic-bifocal-30.csv');assert.deepEqual(await readFile(await download.path()),Buffer.from(csv))
  await page.getByLabel('Import mode',{exact:true}).selectOption('append')
  await file.setInputFiles({name:'synthetic-bifocal-31.csv',mimeType:'text/csv',buffer:Buffer.from('id,date,region,amount\n3,02/01/2026,West,$100.00\n')})
  await page.getByRole('button',{name:'Preview import',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Plan ready'}).waitFor()
  await page.getByLabel('I reviewed this exact plan and its fingerprint',{exact:true}).check()
  await page.getByRole('button',{name:'Apply import',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Import completed and reconciled'}).waitFor()
  current=await(await context.request.get(`${origin}/api/operator/datasets/${dataset}`)).json();assert.equal(current.table.rows.length,3)
  await page.getByRole('button',{name:'Undo import',exact:true}).first().click()
  await page.getByRole('status').filter({hasText:'Import undone'}).waitFor()
  current=await(await context.request.get(`${origin}/api/operator/datasets/${dataset}`)).json();assert.equal(current.table.rows.length,2)
  await file.setInputFiles({name:'synthetic-bifocal-32.csv',mimeType:'text/csv',buffer:Buffer.from('id,date,region,amount\n4,02/02/2026,West,not-money\n')})
  await page.getByRole('button',{name:'Preview import',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Import blocked'}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Apply import',exact:true}).isDisabled(),true)
  assert.match(await page.locator('#error-list').innerText(),/money/)
  await shot('blocked')
  await page.getByRole('button',{name:'Cancel import',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Import cancelled'}).waitFor()
  await page.getByRole('button',{name:'Load dataset',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Dataset state and history loaded'}).waitFor()
  await page.getByText('Erase this dataset and retained imports',{exact:true}).click()
  await page.getByLabel('Type dataset id to confirm',{exact:true}).fill(dataset)
  await page.getByRole('button',{name:'Erase reviewed dataset',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Dataset erased'}).waitFor()
  assert.match(await page.locator('#current-table').innerText(),/fresh installation without the journal cannot detect/)
  assert.equal((await context.request.get(`${origin}/api/operator/datasets/${dataset}`)).status(),404)
  assert.equal(await page.locator('#review').isHidden(),true);assert.equal(await file.inputValue(),'')
  await shot('erased')
  const bookId=`synthetic-bifocal-ui-workbook-${width}`
  await page.getByLabel('Dataset id',{exact:true}).fill(bookId)
  assert.equal(await page.locator('#current-table').innerText(),'');assert.equal(await page.locator('#history-list button').count(),0)
  await page.getByLabel('Import mode',{exact:true}).selectOption('replace')
  await page.getByLabel('Sheet name (XLSX)',{exact:true}).fill('January')
  await file.setInputFiles({name:'synthetic-bifocal-40.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:workbookBytes})
  await page.getByRole('button',{name:'Preview import',exact:true}).click();await page.getByRole('status').filter({hasText:'Plan ready'}).waitFor()
  assert.match(await page.locator('#source').innerText(),/January, February/);assert.match(await page.locator('#source').innerText(),/SUM\(1200,34.56\)/)
  await shot('workbook-review')
  await page.getByLabel('I reviewed this exact plan and its fingerprint',{exact:true}).check();await page.getByRole('button',{name:'Apply import',exact:true}).click();await page.getByRole('status').filter({hasText:'Import completed and reconciled'}).waitFor()
  await page.getByLabel('Import mode',{exact:true}).selectOption('append');await page.getByLabel('Sheet name (XLSX)',{exact:true}).fill('February')
  await page.getByRole('button',{name:'Preview import',exact:true}).click();await page.getByRole('status').filter({hasText:'Plan ready'}).waitFor()
  await page.getByLabel('I reviewed this exact plan and its fingerprint',{exact:true}).check();await page.getByRole('button',{name:'Apply import',exact:true}).click();await page.getByRole('status').filter({hasText:'Import completed and reconciled'}).waitFor()
  assert.equal((await(await context.request.get(`${origin}/api/operator/datasets/${bookId}`)).json()).table.rows.length,3)
  await page.getByRole('button',{name:'Undo import',exact:true}).first().click();await page.getByRole('status').filter({hasText:'Import undone'}).waitFor()
  assert.equal((await(await context.request.get(`${origin}/api/operator/datasets/${bookId}`)).json()).table.rows.length,2)
  const bookDownloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Download original',exact:true}).first().click();const bookDownload=await bookDownloadPromise;assert.deepEqual(await readFile(await bookDownload.path()),workbookBytes)
  await shot('workbook-undone')
  await page.getByLabel('Type dataset id to confirm',{exact:true}).fill(bookId)
  await page.getByRole('button',{name:'Erase reviewed dataset',exact:true}).click();await page.getByRole('status').filter({hasText:'Dataset erased'}).waitFor()

 }
 console.log('File browser: upload/detection/review/apply/reconciliation/append/Undo/errors/consented erasure at 1440/390 passed')
}
