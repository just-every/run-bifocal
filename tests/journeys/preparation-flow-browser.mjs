import assert from 'node:assert/strict'

export async function provePreparationFlowBrowser({origin,page,call,proveScreen,flow}){
 const path='/preparations/'+flow.preparationId
 await page.goto(origin+'/app/import#preparation')
 await page.getByLabel('Preparation ID',{exact:true}).fill(flow.preparationId)
 await page.locator('#prep-flow summary').click()
 await page.getByLabel('Imported flow project ID',{exact:true}).fill(flow.projectId)
 await page.getByLabel('Flow source bindings (JSON)',{exact:true}).fill(JSON.stringify(flow.request.bindings))
 await page.getByRole('button',{name:'Review imported preparation flow',exact:true}).click()
 await page.locator('#prep-flow-status').filter({hasText:'Supported flow loaded'}).waitFor()
 assert.equal(await page.getByLabel('Source dataset ID',{exact:true}).inputValue(),'synthetic-bifocal-170')
 const mappings=page.getByRole('table',{name:'Original preparation step mappings',exact:true})
 assert.equal(await mappings.locator('tbody tr').count(),3)
 assert.match(await mappings.innerText(),/Excel\.CurrentWorkbook/)
 assert.match(await page.locator('#prep-flow-report').innerText(),/unverified/)
 await proveScreen('preparation-original-mapping')
 await page.getByRole('button',{name:'Review preparation',exact:true}).click()
 await page.locator('#prep-status').filter({hasText:'Draft reviewed'}).waitFor()
 const rows=()=>page.getByRole('table',{name:'Reviewed output rows',exact:true}).locator('tbody tr').evaluateAll(rows=>rows.map(row=>[...row.cells].map(cell=>cell.textContent)))
 assert.deepEqual(await rows(),[['1.25','true','West'],['3.5','false','East']])
 await page.getByLabel('I reviewed these exact rows, errors, source revisions and digest',{exact:true}).check()
 await page.getByRole('button',{name:'Save reviewed draft',exact:true}).click()
 await page.locator('#prep-status').filter({hasText:'Draft saved as revision 1'}).waitFor()
 await page.getByLabel('Editing form',{exact:true}).selectOption('sql')
 const sql=await page.getByLabel('SQL statements',{exact:true}).inputValue()
 await page.getByLabel('SQL statements',{exact:true}).fill(sql.replace('SELECT DISTINCT * FROM INPUT;',''))
 await page.getByRole('button',{name:'Review preparation',exact:true}).click()
 await page.locator('#prep-status').filter({hasText:'Draft reviewed'}).waitFor()
 assert.deepEqual(await rows(),[['1.25','true','West'],['1.25','true','West'],['3.5','false','East']])
 await proveScreen('preparation-original-native-edit')
 await page.getByLabel('I reviewed these exact rows, errors, source revisions and digest',{exact:true}).check()
 await page.getByRole('button',{name:'Save reviewed draft',exact:true}).click()
 await page.locator('#prep-status').filter({hasText:'Draft saved as revision 2'}).waitFor()
 const edited={...flow.review.document,steps:[...flow.review.document.steps,{op:'calculate',name:'squared',operator:'multiply',left:'quantity',right:'quantity'}]}
 const review=await call(path+'/review',{document:edited,previousVersion:2},200)
 assert.deepEqual(review.output.rows,[['1.25','true','West','1.5625'],['3.5','false','East','12.25']])
 await call(path+'/save',{document:edited,previousVersion:2,reviewedDigest:review.digest})
 const prior=await call(path+'/review',{document:flow.review.document,previousVersion:3},200)
 const restored=await call(path+'/restore',{restoreVersion:1,previousVersion:3,reviewedDigest:prior.digest})
 assert.equal(restored.version,4);assert.deepEqual(restored.output,flow.review.output)
 const history=await call(path)
 assert.deepEqual(history.revisions.map(r=>r.version),[1,2,3,4])
 assert.deepEqual(history.revisions[0].document.imported,history.revisions[3].document.imported)
 assert.deepEqual(history.revisions[0].lineage,history.revisions[3].lineage)
 await page.getByRole('button',{name:'Load saved preparation',exact:true}).click()
 await page.locator('#prep-status').filter({hasText:'Current saved draft loaded'}).waitFor()
 await page.getByRole('button',{name:'Review preparation',exact:true}).click()
 await page.locator('#prep-status').filter({hasText:'Draft reviewed'}).waitFor()
 assert.deepEqual(await rows(),[['1.25','true','West'],['3.5','false','East']])
 await proveScreen('preparation-original-restored')
 const output='synthetic-bifocal-180',publication=await call(path+'/publish-review',{dataset:output,version:4},200)
 await call(path+'/publish',{dataset:output,version:4,reviewedDigest:publication.digest})
 assert.deepEqual((await call('/datasets/'+output)).table.rows,flow.review.output.rows)
 await flow.erase()
 await call(path,undefined,404);await call('/datasets/'+output,undefined,404)
 await page.getByRole('button',{name:'Load saved preparation',exact:true}).click()
 await page.locator('#prep-status').filter({hasText:'No saved preparation with this ID'}).waitFor()
 await proveScreen('preparation-original-erased')
 console.log('Original preparation intake: complete step inventory, supported native edit and API revisions, restored lineage and source erasure passed; original-runtime parity remains unverified')
}
